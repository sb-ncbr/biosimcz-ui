// Turns the raw Figma SVG exports in ./figma into figma-icons.generated.tsx and manifest.json.
// Run: node src/shared/ui/icons/generate-icons.mjs
// Single-colour glyphs are rewritten to currentColor so e-infra tokens colour them (decision U5).
// Molecule and shape tiles keep their illustrative colours inside the SVG and are referenced as images.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = dirname(fileURLToPath(import.meta.url));
const figmaDir = join(dir, "figma");

const EXPORTED_AT = "2026-09-29";
// nodeId null = file comes from plans/design/figma/assets/final/<frame>/ (per-node folder, verified), node not re-queried.
