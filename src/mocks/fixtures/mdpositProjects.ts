type Seed = {
  name: string;
  description: string;
  authors: string[];
  groups: string[];
  program: string | null;
  version?: string;
  ff: string[];
  wat: string | null;
  ensemble: string | null;
  method?: string;
  type?: string;
  collections: string[];
  temp: number | null;
  timestep: number | null;
  atoms: number;
  lengthNs: number;
  replicas?: number;
  files?: string[];
  protseq?: string[];
};

const CC_BY = {
  LICENSE: "This trajectory dataset is released under a Creative Commons Attribution 4.0 International Public License",
  LINKCENSE: "https://creativecommons.org/licenses/by/4.0/",
};

const FILES = ["structure.pdb", "trajectory.xtc", "topology.top", "average.pdb"];

// Ids and dates grow with the index, so sorting by `_id` (the `identifier` here) means oldest first.
const build = (seed: Seed, index: number) => {
  const number = index + 1;
  const replicas = seed.replicas ?? 1;
  const files = seed.files ?? FILES;
  return {
    identifier: `6650f1c2a1b2c3d4e5f6${number.toString(16).padStart(4, "0")}`,
    accession: `MD-A${String(number).padStart(5, "0")}`,
    published: true,
    metadata: {
      NAME: seed.name,
      DESCRIPTION: seed.description,
      AUTHORS: seed.authors,
      GROUPS: seed.groups,
      PROGRAM: seed.program,
      VERSION: seed.version ?? null,
      TYPE: seed.type ?? "trajectory",
      METHOD: seed.method ?? "Classical MD",
      ...CC_BY,
      CITATION: "DOI: 10.0000/example.2026",
      THANKS: null,
      CONTACT: "data@example.org",
      PROTSEQ: seed.protseq ?? [],
      NUCLSEQ: [],
      LENGTH: seed.lengthNs,
      TIMESTEP: seed.timestep,
      FF: seed.ff,
      TEMP: seed.temp,
      WAT: seed.wat,
      ENSEMBLE: seed.ensemble,
      SYSTATS: seed.atoms,
      COLLECTIONS: seed.collections,
      PDBIDS: [],
      REFERENCES: [],
      LINKS: [{ name: "Paper", url: "https://example.org/paper" }],
      frameCount: Math.round(seed.lengthNs * 100),
    },
    chains: ["A"],
    mdref: 0,
    mds: Array.from({ length: replicas }, (_, replica) => `replica ${replica + 1}`),
    files,
    mdcount: replicas,
    mdNumber: replicas,
    creationDate: new Date(Date.UTC(2026, 0, 1 + number)).toISOString(),
    updateDate: new Date(Date.UTC(2026, 5, 1 + number)).toISOString(),
    totalSize: 1_000_000 * number,
    totalFrames: Math.round(seed.lengthNs * 100),
  };
};


