import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

type Json = null | boolean | number | string | Json[] | { [key: string]: Json };

const ROOT = process.cwd();
const SOURCE = join(ROOT, "openapi", "mdposit.source.json");
const PATCHED = join(ROOT, "openapi", "mdposit.patched.json");
const GENERATED = join(ROOT, "src", "server", "backends", "mdposit", "generated", "schema.d.ts");
const HEADER = "/* GENERATED by scripts/fix-openapi.ts (npm run gen:api). DO NOT EDIT. */\n\n";

const isObject = (value: Json | undefined): value is { [key: string]: Json } =>
  typeof value === "object" && value !== null && !Array.isArray(value);

const resolvePointer = (root: Json, pointer: string): Json => {
  const target = pointer
    .slice(2)
    .split("/")
    .reduce<Json | undefined>((node, part) => (isObject(node) ? node[decodeURIComponent(part)] : undefined), root);
  if (target === undefined) throw new Error(`Unresolvable $ref ${pointer}`);
  return target;
};

// The spec is Swagger 2 flavoured: refs point into a top-level "definitions" block that OpenAPI 3 does not have.
// Inlining a deep copy is the least invasive fix and keeps the source file untouched.
const inlineDefinitionRefs = (node: Json, root: Json): Json => {
  if (Array.isArray(node)) return node.map((child) => inlineDefinitionRefs(child, root));
  if (!isObject(node)) return node;
  const ref = node["$ref"];
  if (typeof ref === "string" && ref.startsWith("#/definitions/")) {
    return inlineDefinitionRefs(structuredClone(resolvePointer(root, ref)), root);
  }
  return Object.fromEntries(Object.entries(node).map(([key, child]) => [key, inlineDefinitionRefs(child, root)]));
};

const buildPatched = (): { patched: string; source: Json } => {
  const source = JSON.parse(readFileSync(SOURCE, "utf8")) as Json;
  const inlined = inlineDefinitionRefs(source, source);
  if (isObject(inlined)) delete inlined["definitions"];
  return { patched: JSON.stringify(inlined, null, 2) + "\n", source: inlined };
};

const generate = async (patchedPath: string): Promise<string> => {
  const ast = await openapiTS(new URL(`file:///${patchedPath.replaceAll("\\", "/")}`));
  return HEADER + astToString(ast);
};

const main = async (): Promise<void> => {
  const check = process.argv.includes("--check");
  const { patched } = buildPatched();
  writeFileSync(PATCHED, patched);
  const generated = await generate(PATCHED);

  if (check) {
    const current = (() => {
      try {
        return readFileSync(GENERATED, "utf8");
      } catch {
        return "";
      }
    })();
    if (current !== generated) {
      console.error("gen:api --check failed: generated MDposit types are stale. Run `npm run gen:api`.");
      process.exit(1);
    }
    console.log("gen:api --check: ok");
    return;
  }

  mkdirSync(dirname(GENERATED), { recursive: true });
  writeFileSync(GENERATED, generated);
  console.log(`gen:api: wrote ${GENERATED}`);
};

main().catch((error: unknown) => {
  console.error(error);
  process.exit(1);
});
